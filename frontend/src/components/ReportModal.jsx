import React, { useState, useEffect, useCallback } from 'react'
import {
  X, Download, Calendar, TrendingUp, FileText,
  ImageOff, ZoomIn, CheckCircle, AlertTriangle,
} from 'lucide-react'

import { API_BASE_URL } from '../services/api'

const API_BASE = API_BASE_URL

/** Confidence colour helpers */
function confidenceColor(pct) {
  if (pct >= 90) return { text: 'text-emerald-400', bar: 'from-emerald-500 to-emerald-400', bg: 'bg-emerald-500/10 border-emerald-500/20' }
  if (pct >= 75) return { text: 'text-yellow-400',  bar: 'from-yellow-500 to-yellow-400',  bg: 'bg-yellow-500/10 border-yellow-500/20'  }
  return          { text: 'text-red-400',    bar: 'from-red-500 to-red-400',    bg: 'bg-red-500/10 border-red-500/20'    }
}

function diseaseBadgeClass(disease) {
  const d = (disease || '').toLowerCase()
  if (d.includes('pneumonia'))   return 'bg-red-500/15 text-red-300 border-red-500/25'
  if (d.includes('cardio'))      return 'bg-orange-500/15 text-orange-300 border-orange-500/25'
  if (d.includes('effusion'))    return 'bg-yellow-500/15 text-yellow-300 border-yellow-500/25'
  if (d.includes('atelectasis')) return 'bg-purple-500/15 text-purple-300 border-purple-500/25'
  if (d.includes('no finding'))  return 'bg-emerald-500/15 text-emerald-300 border-emerald-500/25'
  return 'bg-clinical-500/15 text-clinical-300 border-clinical-500/25'
}

/**
 * ReportModal — full-detail overlay for a single X-ray report.
 *
 * Props:
 *   report  — the report object from /reports API
 *   onClose — callback to clear selectedReport
 */
function ReportModal({ report, onClose }) {
  const [imgError,  setImgError]  = useState(false)
  const [zoomed,    setZoomed]    = useState(false)
  const [pdfLoading, setPdfLoading] = useState(false)

  const pct    = Math.round(report.confidence * 100)
  const colors = confidenceColor(pct)

  const date = new Date(report.created_at)
  const dateStr = date.toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' })
  const timeStr = date.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })

  // image_url comes from backend (/reports now returns the full URL)
  const imageUrl = report.image_url || `${API_BASE}${report.image_path}`

  /* ── Close on Escape key ─────────────────────────────────── */
  const handleKeyDown = useCallback((e) => {
    if (e.key === 'Escape') onClose()
  }, [onClose])

  useEffect(() => {
    document.addEventListener('keydown', handleKeyDown)
    document.body.style.overflow = 'hidden'
    return () => {
      document.removeEventListener('keydown', handleKeyDown)
      document.body.style.overflow = ''
    }
  }, [handleKeyDown])

  /* ── PDF download (browser print-to-PDF) ─────────────────── */
  const handleDownloadPDF = () => {
    setPdfLoading(true)
    const win = window.open('', '_blank')
    const content = `
      <!DOCTYPE html>
      <html>
      <head>
        <title>X-ray Report #${report.id} — ${report.disease}</title>
        <style>
          body { font-family: 'Segoe UI', sans-serif; max-width: 700px; margin: 40px auto; color: #1e293b; }
          h1   { font-size: 22px; margin-bottom: 4px; }
          .meta{ color: #64748b; font-size: 13px; margin-bottom: 24px; }
          .badge { display:inline-block; padding:3px 12px; border-radius:999px; background:#eff6ff; color:#1d4ed8; font-weight:600; font-size:13px; margin-bottom:16px; }
          .conf { font-size: 28px; font-weight: 700; color: #10b981; }
          .bar-wrap { background:#e2e8f0; border-radius:8px; height:8px; margin:8px 0 24px; }
          .bar { background: linear-gradient(90deg,#10b981,#3b82f6); height:8px; border-radius:8px; width:${pct}%; }
          pre  { white-space: pre-wrap; font-family: 'Courier New', monospace; font-size: 13px; background:#f8fafc; border:1px solid #e2e8f0; border-radius:8px; padding:20px; line-height:1.7; }
          img  { max-width:100%; border-radius:8px; margin-bottom:20px; border:1px solid #e2e8f0; }
          .footer { margin-top:32px; font-size:11px; color:#94a3b8; border-top:1px solid #e2e8f0; padding-top:16px; }
        </style>
      </head>
      <body>
        <h1>AI X-ray Radiology Report</h1>
        <div class="meta">Report #${report.id} &nbsp;·&nbsp; ${dateStr} at ${timeStr}</div>
        <div class="badge">${report.disease}</div>

        <p><strong>AI Confidence Score</strong></p>
        <div class="conf">${pct}%</div>
        <div class="bar-wrap"><div class="bar"></div></div>

        ${!imgError ? `<img src="${imageUrl}" alt="X-ray image" />` : ''}

        <p><strong>Full Radiology Report</strong></p>
        <pre>${report.report_text || 'Report text not available for this entry.'}</pre>

        <div class="footer">
          ⚠ This is an AI-generated draft. A licensed radiologist must review and sign off before any clinical decision is made.<br/>
          Generated by AI X-ray Diagnosis System · ${new Date().toLocaleDateString()}
        </div>
      </body>
      </html>
    `
    win.document.write(content)
    win.document.close()
    win.focus()
    setTimeout(() => { win.print(); setPdfLoading(false) }, 600)
  }

  return (
    /* ── Overlay ─────────────────────────────────────────────── */
    <div
      role="dialog"
      aria-modal="true"
      aria-label={`Report details: ${report.disease}`}
      className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6"
      onClick={(e) => { if (e.target === e.currentTarget) onClose() }}
    >
      {/* Blurred dark backdrop */}
      <div className="absolute inset-0 bg-slate-950/80 backdrop-blur-md" onClick={onClose} />

      {/* Modal panel */}
      <div className="relative z-10 w-full max-w-3xl max-h-[92vh] flex flex-col bg-slate-900 border border-slate-700/60 rounded-3xl shadow-2xl overflow-hidden animate-scale-in">

        {/* ── Header ─────────────────────────────────────────── */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 flex-shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-clinical-500/10 border border-clinical-500/20">
              <FileText className="w-4 h-4 text-clinical-400" />
            </div>
            <div>
              <h2 className="font-display font-bold text-white text-base leading-tight">
                Radiology Report
              </h2>
              <p className="text-xs text-slate-500">Report #{report.id}</p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            {/* Download PDF */}
            <button
              id={`btn-download-pdf-${report.id}`}
              onClick={handleDownloadPDF}
              disabled={pdfLoading}
              className="hidden sm:flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold text-slate-300 bg-slate-800 border border-slate-700 hover:border-clinical-500/50 hover:text-clinical-300 transition-all disabled:opacity-50"
            >
              <Download className="w-3.5 h-3.5" />
              {pdfLoading ? 'Preparing…' : 'Download PDF'}
            </button>

            {/* Close */}
            <button
              id={`btn-close-modal-${report.id}`}
              onClick={onClose}
              aria-label="Close report"
              className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-slate-700 transition-all"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* ── Scrollable body ─────────────────────────────────── */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6">

          {/* Top grid — image + summary */}
          <div className="grid sm:grid-cols-2 gap-5">

            {/* X-ray image */}
            <div className="relative group rounded-2xl overflow-hidden bg-slate-950 border border-slate-800 aspect-square flex items-center justify-center">
              {!imgError ? (
                <>
                  <img
                    src={imageUrl}
                    alt={`Chest X-ray — ${report.disease}`}
                    className="w-full h-full object-contain"
                    onError={() => setImgError(true)}
                  />
                  {/* Zoom overlay */}
                  <button
                    onClick={() => setZoomed(true)}
                    className="absolute inset-0 bg-slate-950/0 group-hover:bg-slate-950/40 flex items-center justify-center transition-all duration-300 opacity-0 group-hover:opacity-100"
                  >
                    <div className="flex items-center gap-2 bg-slate-900/90 border border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-300 font-medium">
                      <ZoomIn className="w-3.5 h-3.5" /> Click to zoom
                    </div>
                  </button>
                </>
              ) : (
                <div className="text-slate-600 flex flex-col items-center gap-2">
                  <ImageOff className="w-10 h-10" />
                  <span className="text-sm">Image unavailable</span>
                </div>
              )}
            </div>

            {/* Summary panel */}
            <div className="space-y-4 flex flex-col justify-center">

              {/* Disease badge */}
              <div>
                <p className="text-xs text-slate-500 mb-1.5 uppercase tracking-widest font-medium">Diagnosis</p>
                <span className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-sm font-bold border ${diseaseBadgeClass(report.disease)}`}>
                  {report.disease.includes('No Finding')
                    ? <CheckCircle className="w-4 h-4" />
                    : <AlertTriangle className="w-4 h-4" />}
                  {report.disease}
                </span>
              </div>

              {/* Confidence */}
              <div>
                <p className="text-xs text-slate-500 mb-1.5 uppercase tracking-widest font-medium">
                  AI Confidence
                </p>
                <div className={`flex items-center justify-between mb-2`}>
                  <span className={`font-display font-extrabold text-3xl ${colors.text}`}>{pct}%</span>
                  <span className={`text-[10px] px-2 py-0.5 rounded-full border font-semibold ${colors.bg} ${colors.text}`}>
                    {pct >= 90 ? 'HIGH' : pct >= 75 ? 'MODERATE' : 'LOW'}
                  </span>
                </div>
                <div className="h-2 bg-slate-800 rounded-full overflow-hidden">
                  <div
                    className={`h-full bg-gradient-to-r ${colors.bar} rounded-full transition-all duration-1000`}
                    style={{ width: `${pct}%` }}
                  />
                </div>
              </div>

              {/* Date / time */}
              <div>
                <p className="text-xs text-slate-500 mb-1.5 uppercase tracking-widest font-medium">Analysed</p>
                <div className="flex items-center gap-2 text-sm text-slate-300">
                  <Calendar className="w-4 h-4 text-slate-500" />
                  {dateStr}
                </div>
                <p className="text-xs text-slate-500 mt-0.5 pl-6">{timeStr}</p>
              </div>

              {/* Mobile PDF button */}
              <button
                onClick={handleDownloadPDF}
                disabled={pdfLoading}
                className="sm:hidden flex items-center gap-2 px-4 py-2.5 rounded-xl bg-slate-800 border border-slate-700 text-sm text-slate-300 hover:border-clinical-500/50 transition-all disabled:opacity-50"
              >
                <Download className="w-4 h-4" />
                {pdfLoading ? 'Preparing…' : 'Download PDF'}
              </button>
            </div>
          </div>

          {/* Divider */}
          <div className="h-px bg-slate-800" />

          {/* Full report text */}
          <div>
            <div className="flex items-center gap-2 mb-3">
              <FileText className="w-4 h-4 text-clinical-400" />
              <p className="text-sm font-semibold text-slate-200">Full Radiology Findings</p>
            </div>
            <div className="bg-slate-950/60 border border-slate-800 rounded-2xl p-5">
              {report.report_text ? (
                <pre className="text-sm text-slate-300 leading-relaxed whitespace-pre-wrap font-mono">
                  {report.report_text}
                </pre>
              ) : (
                <p className="text-sm text-slate-500 italic">
                  Full report text is not available for this entry.
                  Re-analyse the image to generate a complete report.
                </p>
              )}
            </div>
          </div>

          {/* Disclaimer */}
          <div className="flex items-start gap-2 px-4 py-3 rounded-xl bg-amber-500/5 border border-amber-500/15">
            <AlertTriangle className="w-4 h-4 text-amber-400 flex-shrink-0 mt-0.5" />
            <p className="text-xs text-amber-200/70 leading-relaxed">
              This is an AI-generated draft. A licensed radiologist must review and sign off
              before any clinical decision is made.
            </p>
          </div>
        </div>
      </div>

      {/* ── Fullscreen zoom lightbox ─────────────────────────── */}
      {zoomed && (
        <div
          className="fixed inset-0 z-[60] bg-black/95 flex items-center justify-center p-4 cursor-zoom-out"
          onClick={() => setZoomed(false)}
        >
          <button
            onClick={() => setZoomed(false)}
            className="absolute top-4 right-4 p-2 rounded-xl bg-slate-800 text-slate-300 hover:text-white transition-colors z-10"
          >
            <X className="w-5 h-5" />
          </button>
          <img
            src={imageUrl}
            alt="X-ray full size"
            className="max-w-full max-h-full object-contain rounded-xl"
            onError={() => { setImgError(true); setZoomed(false) }}
          />
        </div>
      )}
    </div>
  )
}

export default ReportModal
